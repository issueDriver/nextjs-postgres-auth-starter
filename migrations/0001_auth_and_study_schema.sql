-- The migration runner owns the transaction and records this file's checksum.
CREATE TABLE IF NOT EXISTS public.books (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  title text NOT NULL,
  "wordCount" integer NOT NULL DEFAULT 0,
  "coverUrl" text NOT NULL,
  "bookId" text NOT NULL,
  tags text[] NOT NULL DEFAULT '{}'::text[],
  status text NOT NULL DEFAULT 'draft'::text,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT books_pkey PRIMARY KEY (id),
  CONSTRAINT "books_bookId_unique" UNIQUE ("bookId"),
  CONSTRAINT books_status_check
    CHECK (status = ANY (ARRAY['published'::text, 'draft'::text])),
  CONSTRAINT books_word_count_check CHECK ("wordCount" >= 0)
);

CREATE TABLE IF NOT EXISTS public.words (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  "wordRank" integer NULL,
  "headWord" text NULL,
  content json NULL,
  "bookId" text NULL,
  CONSTRAINT words_pkey PRIMARY KEY (id),
  CONSTRAINT "words_bookId_books_bookId_fk"
    FOREIGN KEY ("bookId") REFERENCES public.books ("bookId")
    ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public."User" (
  id serial PRIMARY KEY,
  email varchar(64) NOT NULL,
  password varchar(64) NOT NULL
);

-- Block registrations while checking and constraining legacy accounts.
LOCK TABLE public."User" IN SHARE ROW EXCLUSIVE MODE;

DO $migration$
DECLARE
  invalid_accounts bigint;
  duplicate_emails bigint;
BEGIN
  SELECT count(*) INTO invalid_accounts
  FROM public."User"
  WHERE email IS NULL OR btrim(email) = ''
     OR password IS NULL OR password = '';

  SELECT count(*) INTO duplicate_emails
  FROM (
    SELECT lower(btrim(email))
    FROM public."User"
    WHERE email IS NOT NULL
    GROUP BY lower(btrim(email))
    HAVING count(*) > 1
  ) AS duplicate_groups;

  IF invalid_accounts > 0 OR duplicate_emails > 0 THEN
    RAISE EXCEPTION
      'Account preflight failed: % invalid rows, % duplicate normalized email groups. Resolve account ownership before migrating.',
      invalid_accounts, duplicate_emails
      USING ERRCODE = '23514';
  END IF;
END
$migration$;

ALTER TABLE public."User" ALTER COLUMN email SET NOT NULL;
ALTER TABLE public."User" ALTER COLUMN password SET NOT NULL;
ALTER TABLE public."User" ADD CONSTRAINT user_email_nonempty
  CHECK (btrim(email) <> '');

CREATE UNIQUE INDEX user_email_normalized_unique
  ON public."User" (lower(btrim(email)));

ALTER TABLE public.books
  ADD COLUMN "studyVersion" integer NOT NULL DEFAULT 1,
  ADD COLUMN "sortOrder" integer NOT NULL DEFAULT 0;
ALTER TABLE public.books ADD CONSTRAINT books_study_version_positive
  CHECK ("studyVersion" >= 1);

ALTER TABLE public.words ADD COLUMN "studyOrder" integer NULL;
ALTER TABLE public.words ADD CONSTRAINT words_study_order_nonnegative
  CHECK ("studyOrder" IS NULL OR "studyOrder" >= 0);

CREATE UNIQUE INDEX words_book_study_order_unique
  ON public.words ("bookId", "studyOrder");
CREATE UNIQUE INDEX words_book_word_unique
  ON public.words ("bookId", id);
CREATE INDEX books_published_order_idx
  ON public.books ("sortOrder", "bookId")
  WHERE status = 'published';

CREATE TABLE public.user_book_progress (
  user_id integer NOT NULL,
  book_id text NOT NULL,
  book_version integer NOT NULL,
  total_words integer NOT NULL,
  learned_count integer NOT NULL DEFAULT 0,
  last_completed_word_id bigint NULL,
  revision integer NOT NULL DEFAULT 0,
  started_at timestamptz NOT NULL DEFAULT now(),
  last_studied_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz NULL,
  CONSTRAINT user_book_progress_pkey PRIMARY KEY (user_id, book_id),
  CONSTRAINT user_book_progress_user_fk
    FOREIGN KEY (user_id) REFERENCES public."User" (id)
    ON UPDATE RESTRICT ON DELETE CASCADE,
  CONSTRAINT user_book_progress_book_fk
    FOREIGN KEY (book_id) REFERENCES public.books ("bookId")
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT user_book_progress_last_word_fk
    FOREIGN KEY (book_id, last_completed_word_id)
    REFERENCES public.words ("bookId", id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT progress_version_positive CHECK (book_version >= 1),
  CONSTRAINT progress_total_positive CHECK (total_words > 0),
  CONSTRAINT progress_count_in_range
    CHECK (learned_count >= 0 AND learned_count <= total_words),
  CONSTRAINT progress_revision_nonnegative CHECK (revision >= 0),
  CONSTRAINT progress_last_word_consistent CHECK (
    (learned_count = 0 AND last_completed_word_id IS NULL)
    OR (learned_count > 0 AND last_completed_word_id IS NOT NULL)
  ),
  CONSTRAINT progress_completion_consistent CHECK (
    (learned_count < total_words AND completed_at IS NULL)
    OR (learned_count = total_words AND completed_at IS NOT NULL)
  )
);

CREATE INDEX user_book_progress_recent_idx
  ON public.user_book_progress (user_id, last_studied_at DESC, book_id);

COMMENT ON COLUMN public.words."studyOrder" IS
  'Immutable zero-based position in the published study sequence; NULL excludes the row from learning.';
COMMENT ON COLUMN public.books."studyVersion" IS
  'Learning content version; metadata-only changes must not increment it.';
COMMENT ON COLUMN public.user_book_progress.learned_count IS
  'Confirmed contiguous prefix length; also the next pending studyOrder.';

-- Some hosted databases grant public-schema tables to browser-facing roles by
-- default. Auth.js uses server-side database access, not those database roles.
REVOKE ALL PRIVILEGES ON TABLE public."User", public.user_book_progress FROM PUBLIC;

DO $migration$
DECLARE
  exposed_role text;
BEGIN
  FOR exposed_role IN
    SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated')
  LOOP
    EXECUTE format(
      'REVOKE ALL PRIVILEGES ON TABLE public."User", public.user_book_progress FROM %I',
      exposed_role
    );
  END LOOP;
END
$migration$;
